function drawExportCanvas() {
  const ctx = exportCanvas.getContext("2d");
  const horizontal = state.layout.orientation === "horizontal";
  const slotW = horizontal ? 320 : 760;
  const slotH = horizontal ? 430 : 520;
  const pad = 70;
  const gap = 28;
  exportCanvas.width = horizontal ? pad * 2 + state.layout.count * slotW + (state.layout.count - 1) * gap : pad * 2 + slotW;
  exportCanvas.height = horizontal ? pad * 2 + slotH + 130 : pad * 2 + state.layout.count * slotH + (state.layout.count - 1) * gap + 130;
  paintFrameBackground(ctx, exportCanvas.width, exportCanvas.height);

  Promise.all(state.photos.map(loadImage)).then((images) => {
    images.forEach((img, index) => {
      const x = horizontal ? pad + index * (slotW + gap) : pad;
      const y = horizontal ? pad : pad + index * (slotH + gap);
      ctx.save();
      if (state.frame.id === "princess") {
        roundedRect(ctx, x, y, slotW, slotH, Math.min(slotW, slotH) / 2);
      } else {
        roundedRect(ctx, x, y, slotW, slotH, 18);
      }
      ctx.clip();
      ctx.filter = getCSSFilterString(state.filter);
      drawCover(ctx, img, x, y, slotW, slotH);
      ctx.restore();
    });
    drawFrameDecorations(ctx, exportCanvas.width, exportCanvas.height);
    drawOverlayText(ctx);
    drawExportStickers(ctx);
    drawExportDoodles(ctx);
  });
}

function drawExportDoodles(ctx) {
  ctx.save();
  state.doodles.forEach((stroke) => {
    if (stroke.points.length < 1) return;
    ctx.beginPath();
    ctx.strokeStyle = stroke.color;
    const scaledWidth = stroke.width * (exportCanvas.width / 420);
    ctx.lineWidth = Math.max(1, scaledWidth);
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    
    const start = stroke.points[0];
    ctx.moveTo((start.x / 100) * exportCanvas.width, (start.y / 100) * exportCanvas.height);
    
    for (let i = 1; i < stroke.points.length; i++) {
      const pt = stroke.points[i];
      ctx.lineTo((pt.x / 100) * exportCanvas.width, (pt.y / 100) * exportCanvas.height);
    }
    ctx.stroke();
  });
  ctx.restore();
}

