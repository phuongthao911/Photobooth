function runCountdown() {
  return new Promise((resolve) => {
    let left = state.countdown;
    const badge = $("#countdownBadge");
    badge.classList.add("show");
    badge.textContent = left;

    const timer = setInterval(() => {
      left -= 1;
      if (left <= 0) {
        clearInterval(timer);
        badge.classList.remove("show");
        badge.textContent = "";
        resolve();
      } else {
        badge.textContent = left;
      }
    }, 1000);
  });
}

